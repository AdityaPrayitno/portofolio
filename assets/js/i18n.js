function applyLang(lang){
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang === 'id' ? 'id' : 'en';
  // text
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){
      // preserve inner HTML for links? Use textContent for simple, innerHTML if contains <br>
      if(el.children.length === 0) el.textContent = dict[key];
      else {
        // if element contains <a> as child (like service link), handle separately via data-i18n for child
        // else replace text nodes
        // simplest: if key is portfolio etc, textContent ok
        // check if dict value contains HTML -> use innerHTML
        if(dict[key].includes('<')) el.innerHTML = dict[key];
        else el.textContent = dict[key];
      }
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if(dict[key] !== undefined) el.placeholder = dict[key];
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.getAttribute('data-i18n-alt');
    if(dict[key] !== undefined) el.alt = dict[key];
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if(dict[key] !== undefined) el.title = dict[key];
  });
  // meta
  if(dict["meta.title"]) document.title = dict["meta.title"];
  const md = document.querySelector('meta[name="description"]');
  if(md && dict["meta.desc"]) md.setAttribute('content', dict["meta.desc"]);
  const ogt = document.querySelector('meta[property="og:title"]');
  if(ogt && dict["meta.ogTitle"]) ogt.setAttribute('content', dict["meta.ogTitle"]);
  const ogd = document.querySelector('meta[property="og:description"]');
  if(ogd && dict["meta.ogDesc"]) ogd.setAttribute('content', dict["meta.ogDesc"]);
  // toggle button active state
  const btnEn = document.getElementById('lang-en');
  const btnId = document.getElementById('lang-id');
  if(btnEn && btnId){
    if(lang==='id'){ btnId.classList.add('active','btn-danger'); btnId.classList.remove('btn-outline-secondary'); btnId.setAttribute('aria-pressed','true'); btnEn.classList.remove('active','btn-danger'); btnEn.classList.add('btn-outline-secondary'); btnEn.setAttribute('aria-pressed','false'); }
    else { btnEn.classList.add('active','btn-danger'); btnEn.classList.remove('btn-outline-secondary'); btnEn.setAttribute('aria-pressed','true'); btnId.classList.remove('active','btn-danger'); btnId.classList.add('btn-outline-secondary'); btnId.setAttribute('aria-pressed','false'); }
  }
  // html lang + hreflang handling for pushState
  try{ localStorage.setItem('lang', lang); }catch(e){}
  // update url without reload for SEO hybrid
  const url = new URL(window.location);
  if(lang==='id' && url.pathname === '/') { history.replaceState(null,'','/id/'); }
  else if(lang==='en' && url.pathname.startsWith('/id')) { history.replaceState(null,'','/'); }
}

function initI18n(){
  const saved = (function(){ try{ return localStorage.getItem('lang'); }catch(e){ return null; } })();
  // strict EN default, no auto browser detect
  const initial = (saved === 'id' || saved === 'en') ? saved : 'en';
  // if URL is /id/ force id
  const isIdPath = window.location.pathname.startsWith('/id');
  const lang = isIdPath ? 'id' : initial;
  applyLang(lang);
  const btnEn = document.getElementById('lang-en');
  const btnId = document.getElementById('lang-id');
  if(btnEn) btnEn.addEventListener('click', ()=> applyLang('en'));
  if(btnId) btnId.addEventListener('click', ()=> applyLang('id'));
}

document.addEventListener('DOMContentLoaded', initI18n);
